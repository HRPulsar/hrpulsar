/** Preset registry. "default" is intentionally absent — it means "inject
 * nothing" and ships the stock globals.css look untouched. */
export const BRAND_THEMES: Record<string, ThemePreset> = {
  teal: TEAL,
  slate: SLATE,
  violet: VIOLET,
};

/** Resolve an env-supplied preset name. Empty, "default", and unknown names
 * all resolve to undefined — the stock theme. */
export function resolveThemePreset(
  name: string | undefined,
): ThemePreset | undefined {
  if (!name || name === "default") return undefined;
  // hasOwn: env values like "constructor" must not resolve members
  // inherited from Object.prototype — that crashes the root layout.
  return Object.hasOwn(BRAND_THEMES, name) ? BRAND_THEMES[name] : undefined;
}
