/**
 * Curated theme presets for white-label installations (HRP-463).
 *
 * A site picks one preset via NEXT_PUBLIC_BRAND_THEME (runtime env, same
 * HRP-393 mechanism as the rest of branding — container restart applies it,
 * no image rebuild). Preset names describe the visual (accent/mood), never
 * a customer or third-party brand.
 *
 * Each preset overrides the full token set from globals.css for both
 * themes, so switching presets never leaves half-styled surfaces. BrandStyle
 * injects `light` at `:root:root` and `dark` at `.dark:root:root` — the
 * doubled selector outranks the stock `:root`/`.dark` blocks regardless of
 * stylesheet order. An explicit NEXT_PUBLIC_BRAND_ACCENT_COLOR still lands
 * on top of the preset's accent (point tweak per site).
 */

export interface ThemePreset {
  light: Record<string, string>;
  dark: Record<string, string>;
}

